"""Development only: generate the R2004 structural skeleton with ezdxf 1.4.4.
No Python/ezdxf dependency is needed by the browser exporter.
Run with ezdxf installed, from the project root.
"""
import io, json, re
from pathlib import Path
import ezdxf

doc = ezdxf.new('R2004')
doc.set_modelspace_vport(330, center=(210,148.5))
stream=io.StringIO(); doc.write(stream)
lines=stream.getvalue().splitlines()
tags=[(int(lines[i]),lines[i+1]) for i in range(0,len(lines),2)]
sections={}; i=0
while i<len(tags):
    if tags[i]==(0,'SECTION'):
        name=tags[i+1][1];j=i+2
        while tags[j]!=(0,'ENDSEC'):j+=1
        if name in ('CLASSES','TABLES','BLOCKS','OBJECTS'):sections[name]=tags[i+2:j]
        i=j
    i+=1
# Default layer 0 is emitted by the exporter along with drawing layers.
a=sections['TABLES']; start=a.index((2,'LAYER'))-1;end=start
while a[end]!=(0,'ENDTAB'):end+=1
sections['TABLES']=a[:start]+[(0,'PAPER_NEST_LAYERS')]+a[end+1:]
# Preserve generated valid default dictionaries/layouts and all their handles.
model=doc.modelspace().block_record.dxf.handle
group=doc.rootdict['ACAD_GROUP'].dxf.handle
# Strip time-dependent metadata values for a reproducible generated template.
sections['OBJECTS']=[(c,re.sub(r'1\.4\.4 @ .*', 'Paper Nest DXF structure', v)) for c,v in sections['OBJECTS']]
header='// Generated by scripts/generate-dxf-template.py using ezdxf 1.4.4.\n// Standard DXF records only; no drawing geometry. Do not hand-edit handles.\n'
data={'modelSpace':model,'groupDictionary':group,'layerTable':doc.layers.head.dxf.handle,'plotStyle':doc.layers.get('0').dxf.plotstyle_handle,'material':doc.layers.get('0').dxf.material_handle,'sections':sections}
Path('dist/dxf-template.js').write_text(header+'export const dxfTemplate = '+json.dumps(data,ensure_ascii=True,separators=(',', ':'))+';\n')
